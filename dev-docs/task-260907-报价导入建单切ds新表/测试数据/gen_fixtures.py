def build_bulk(n, name):
    """AC-20 大单量：n 条客户料号 / n 个料号，每料号 1 条 BOM + 1 条元素 BOM。"""
    wb = load_template()
    mats, cps, boms, ebs = [], [], [], []
    for i in range(1, n + 1):
        m = "%sB%05d" % (P, i)
        mats.append({'销售料号': m, '产品分类': '000000', '品名': '批量件%d' % i, '规格': 'BULK',
                     '尺寸': '1×1', '旧料号': None, '单重': 1.0, '生产料号': '%sBP%05d' % (P, i),
                     '类型': '零件'})
        cps.append({'客户编号': CUST, '客户料号名称': '批量客户件%d' % i,
                    '客户产品编号': 'ZT-BULK-%05d' % i, '客户图号': 'DWG-BULK-%05d' % i, '销售料号': m})
        boms.append({'销售料号': m, '项次': 1, '投入料号': RM1, '单重': 0.8, '产出料号类型': '成品',
                     '组成数量': 1, '材料毛重': 0.8, '材料净重': 0.78, '重量单位': 'g',
                     '材料占比（%）': 100, '损耗率（%）': 2, '不良率（%）': 1})
        ebs.append({'销售料号': m, '材质料号': '992', '项次': 1, '元素': 'Ag', '组成含量（%）': 70,
                    '损耗率%': 1.5, '毛用量': 8.684, '毛用量单位': 'g', '净用量': 8.554,
                    '净用量单位': 'g', '回收折扣(%)': 5, '回收量': '0.13'})
    # RM1 自身也要在物料表里，否则 LEFT JOIN 拿不到品名（不影响行数，但影响可读性）
    mats.append({'销售料号': RM1, '产品分类': '000000', '品名': '银镍带材', '规格': 'AgNi10',
                 '尺寸': '3×0.5', '旧料号': None, '单重': 0.8, '生产料号': P + 'P04', '类型': '零件'})

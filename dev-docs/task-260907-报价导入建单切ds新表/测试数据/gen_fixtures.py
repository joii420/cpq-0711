def headers(ws):
    return [ws.cell(1, c).value for c in range(1, ws.max_column + 1)]


def load_template():
    """只取表头，丢掉标记行与模板自带的示例数据行。

    🚩 建表规范 Excel 的带版本 sheet 第 2 行是「轴/对比项」标记行，**真实导入数据里没有这一行**
       （task-260902 B-21 已实证，生产侧 firstDataRow 恒为第 2 行）。不删它 = 夹具行号与实现各说各话。
    """
    wb = openpyxl.load_workbook(SRC)
    assert wb.sheetnames == SHEETS, f"模板 sheet 与预期不符: {wb.sheetnames}"
    for ws in wb.worksheets:
        if ws.max_row > 1:
            ws.delete_rows(2, ws.max_row - 1)
        # 删干净后校验：表头行必须还在，且不含标记词
        h = [v for v in headers(ws) if v]
        assert h and '轴' not in h and '对比项' not in h, f"{ws.title} 表头被删坏: {h}"
    return wb


def put(ws, rows):
    """rows: list of dict(列名 -> 值)。按表头定位列，列名写错立刻硬失败。"""
    hdr = headers(ws)
    idx = {h: i + 1 for i, h in enumerate(hdr) if h is not None}
    for r, row in enumerate(rows, start=2):
        for k, v in row.items():
            if k not in idx:
                raise KeyError(f"sheet「{ws.title}」没有列「{k}」，实际列: {hdr}")
            ws.cell(r, idx[k]).value = v



package com.cpq.dataset.versioning;

import com.cpq.dataset.registry.ColumnDef;
import com.cpq.dataset.registry.QuoteRegistry;
import com.cpq.dataset.registry.SheetDef;
import jakarta.persistence.EntityManager;
import jakarta.persistence.Query;
import org.junit.jupiter.api.Test;

import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.concurrent.atomic.AtomicReference;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.ArgumentMatchers.anyString;
import static org.mockito.Mockito.doAnswer;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.when;

class PlainTableWriterTest {

    @Test
    void keepsCustomerPartVersionOutOfExcelColumns() {
        SheetDef customerPart = new QuoteRegistry().sheets().stream()
                .filter(s -> "ds_quote_customer_part".equals(s.tableName))
                .findFirst()
                .orElseThrow();

        assertFalse(customerPart.persistedColumns().stream()
                .anyMatch(column -> "version".equals(column.name)),
                "version is a server-owned column and must not be required in Excel");
        assertTrue(customerPart.internalColumns().contains("version"));
        assertEquals("1", PlainTableWriter.generatedExpression(customerPart, "version"));

        EntityManager em = mock(EntityManager.class);
        Query query = mock(Query.class);
        AtomicReference<String> generatedSql = new AtomicReference<>();
        when(em.createNativeQuery(anyString())).thenAnswer(invocation -> {
            generatedSql.set(invocation.getArgument(0, String.class));
            return query;
        });
        when(query.getResultList()).thenReturn(List.of(Boolean.TRUE));
        List<String> boundNames = new ArrayList<>();
        doAnswer(invocation -> {
            boundNames.add(invocation.getArgument(0, String.class));
            return query;
        }).when(query).setParameter(anyString(), any());

        PlainTableWriter writer = new PlainTableWriter();
        writer.em = em;
        Map<String, Object> row = new LinkedHashMap<>();
        for (ColumnDef column : customerPart.persistedColumns()) {
            row.put(column.name, switch (column.name) {
                case "customer_no" -> "C-TEST";
                case "customer_product_no" -> "CP-TEST";
                default -> null;
            });
        }

        writer.upsert(customerPart, "C-TEST", List.of(row), "IMPORT", "test");

        assertTrue(generatedSql.get().contains("version = ds_quote_customer_part.version + 1"));
        assertFalse(boundNames.contains("p0_6"), "version must be generated by SQL, not bound from Excel");
        assertTrue(boundNames.contains("p0_7"), "source must retain its slot after internal version");
    }

    @Test
    void skipsBindParameterForGeneratedVatColumn() {
        SheetDef material = new QuoteRegistry().sheets().stream()
                .filter(s -> "ds_quote_material".equals(s.tableName))
                .findFirst()
                .orElseThrow();

        int profitIndex = indexOfPersisted(material, "profit");
        int generatedVatIndex = material.persistedColumns().size();

        EntityManager em = mock(EntityManager.class);
        Query query = mock(Query.class);
        when(em.createNativeQuery(anyString())).thenReturn(query);
        when(query.getResultList()).thenReturn(List.of(Boolean.TRUE));
        List<String> boundNames = new ArrayList<>();
        doAnswer(invocation -> {
            boundNames.add(invocation.getArgument(0, String.class));
            return query;
        }).when(query).setParameter(anyString(), any());

        PlainTableWriter writer = new PlainTableWriter();
        writer.em = em;

        Map<String, Object> row = new LinkedHashMap<>();
        for (ColumnDef column : material.persistedColumns()) {
            row.put(column.name, "material_no".equals(column.name) ? "M-TEST" : null);
        }

        PlainTableWriter.UpsertResult result = writer.upsert(
                material, "CUST-TEST", List.of(row), "IMPORT", "test");

        assertEquals(1, result.inserted());
        assertEquals(0, result.updated());
        assertTrue(boundNames.contains("p0_" + profitIndex),
                "profit is a persisted Excel value and must not be mistaken for generated VAT");
        assertFalse(boundNames.contains("p0_" + generatedVatIndex),
                "tax_category_id is a SQL expression, not a bind parameter");
    }

    private static int indexOfPersisted(SheetDef sheet, String name) {
        for (int i = 0; i < sheet.persistedColumns().size(); i++) {
            if (name.equals(sheet.persistedColumns().get(i).name)) return i;
        }
        throw new AssertionError("missing persisted column: " + name);
    }
}
